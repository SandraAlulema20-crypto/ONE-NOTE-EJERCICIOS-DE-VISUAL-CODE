public class TipoBoolean {
    public static void main(String[] args) {
        // El tipo boolean SOLO admite true o false
        boolean esVerdadero = true;
        boolean esFalso = false;
        
        System.out.println("Valor 1: " + esVerdadero); // true
        System.out.println("Valor 2: " + esFalso);     // false
        
        // Equivalencia numérica (solo como referencia)
        System.out.println("\nEquivalencia lógica:");
        System.out.println("true  → 1");
        System.out.println("false → 0");
    }
}
